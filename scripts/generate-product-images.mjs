import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, "..");
const stagesDir = path.join(root, "public", "products");
const outDir = path.join(root, "lib", "generated");
const outFile = path.join(outDir, "product-images.ts");

const STAGES = ["34", "42", "65", "120"];
const IMAGE_RE = /\.(jpe?g|png|webp|gif)$/i;

function numericSort(a, b) {
  const na = parseInt(path.parse(a).name, 10);
  const nb = parseInt(path.parse(b).name, 10);
  if (!Number.isNaN(na) && !Number.isNaN(nb) && na !== nb) return na - nb;
  return a.localeCompare(b, undefined, { numeric: true });
}

/** @type {Record<string, string[]>} */
const byStage = {};

for (const stage of STAGES) {
  const dir = path.join(stagesDir, stage);
  if (!fs.existsSync(dir)) {
    byStage[stage] = [];
    continue;
  }
  const files = fs
    .readdirSync(dir)
    .filter((f) => IMAGE_RE.test(f))
    .sort(numericSort)
    .map((f) => `/products/${stage}/${f}`);
  byStage[stage] = files;
}

fs.mkdirSync(outDir, { recursive: true });

const body = `// Auto-generated by scripts/generate-product-images.mjs — do not edit
export const PRODUCT_IMAGES_BY_STAGE = ${JSON.stringify(byStage, null, 2)} as const;

export type PriceStageFolder = keyof typeof PRODUCT_IMAGES_BY_STAGE;

export function imagesForStage(stage: PriceStageFolder): string[] {
  return [...PRODUCT_IMAGES_BY_STAGE[stage]];
}
`;

fs.writeFileSync(outFile, body, "utf8");

const total = Object.values(byStage).reduce((n, arr) => n + arr.length, 0);
console.log(`Generated ${outFile} (${total} images across ${STAGES.length} stages)`);
for (const [stage, files] of Object.entries(byStage)) {
  console.log(`  ${stage}: ${files.length} files`);
}
